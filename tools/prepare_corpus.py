#!/usr/bin/env python3
"""Generate local synthetic media and controlled mutations; no downloads."""
import argparse
import json
from pathlib import Path

from corpus import ROOT, bounded_run, file_identity, raw_framing, require

COMMON = ["-hide_banner", "-v", "error", "-nostdin", "-n"]
RECIPES = {
    "generated-avc-aac.flv": COMMON + [
        "-f", "lavfi", "-i", "testsrc2=size=160x90:rate=25", "-f", "lavfi", "-i",
        "sine=frequency=997:sample_rate=44100", "-t", "2", "-map_metadata", "-1",
        "-c:v", "libx264", "-threads", "1", "-pix_fmt", "yuv420p", "-g", "25", "-bf", "2",
        "-c:a", "aac", "-b:a", "64k", "-flvflags", "no_metadata", "-f", "flv"],
    "generated-mp3.flv": COMMON + [
        "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=44100", "-t", "2", "-map_metadata", "-1",
        "-c:a", "libmp3lame", "-threads", "1", "-b:a", "128k", "-flvflags", "no_metadata", "-f", "flv"],
    "generated-aac.flv": COMMON + [
        "-f", "lavfi", "-i", "sine=frequency=880:sample_rate=48000", "-t", "2", "-map_metadata", "-1",
        "-c:a", "aac", "-threads", "1", "-b:a", "64k", "-flvflags", "no_metadata", "-f", "flv"],
}


def known_identity(path):
    matches = []
    for manifest_path in (ROOT / "testdata/manifests").glob("*.sample.json"):
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if manifest["file"]["name"] == path.name:
            matches.append(manifest["file"])
    require(len(matches) == 1, "existing file has no unique registered identity")
    expected = matches[0]
    require(file_identity(path) == (expected["sizeBytes"], expected["sha256"]), "existing/generated bytes differ from registered identity")


def create_derived(directory):
    aac = directory / "generated-aac.flv"
    mp3 = directory / "generated-mp3.flv"
    known_identity(aac)
    known_identity(mp3)
    data = bytearray(mp3.read_bytes())
    _, records, _ = raw_framing(mp3)
    trailer = records[0]["offset"] + 11 + records[0]["dataSize"]
    data[trailer:trailer + 4] = b"\0\0\0\0"
    artifacts = {"derived-aac-truncated.flv": aac.read_bytes()[:-2],
                 "derived-mp3-bad-previous.flv": data}
    for name, payload in artifacts.items():
        path = directory / name
        if path.exists():
            known_identity(path)
            require(path.read_bytes() == payload, "refusing to overwrite a different derived fixture")
        else:
            with path.open("xb") as output:
                output.write(payload)
        known_identity(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--ffmpeg", type=Path)
    parser.add_argument("--only-derived", action="store_true")
    args = parser.parse_args()
    directory = args.output_dir.resolve()
    directory.mkdir(parents=True, exist_ok=True)
    if not args.only_derived:
        require(args.ffmpeg is not None, "--ffmpeg is required for media generation")
        for name, recipe in RECIPES.items():
            path = directory / name
            if path.exists():
                known_identity(path)
                continue
            code, _, _ = bounded_run([args.ffmpeg.resolve(strict=True), *recipe, path], timeout=30, limit=1 << 20)
            require(code == 0, "FFmpeg generation failed; partial artifact retained for inspection")
            known_identity(path)
    create_derived(directory)
    print(json.dumps({"prepared": sorted([*RECIPES, "derived-aac-truncated.flv", "derived-mp3-bad-previous.flv"])}))


if __name__ == "__main__":
    main()
